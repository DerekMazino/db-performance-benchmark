-- 1. Crear la tabla particionada por rangos de fecha mensuales
CREATE TABLE ledger_transactions_part (
    transaction_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    account_id        NUMBER NOT NULL,
    transaction_date  TIMESTAMP NOT NULL,
    transaction_type  VARCHAR2(20) NOT NULL,
    amount            NUMBER(12, 2) NOT NULL,
    status            VARCHAR2(20) NOT NULL,
    payload_metadata  VARCHAR2(250),
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
PARTITION BY RANGE (transaction_date)
INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
(
    PARTITION p_initial VALUES LESS THAN (TIMESTAMP '2025-01-01 00:00:00')
);

