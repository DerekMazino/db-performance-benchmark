SET ECHO OFF;
SET FEEDBACK OFF;

ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = BENCHMARK_USER;

-- Tabla para almacenar excepciones capturadas por SQL%BULK_EXCEPTIONS
CREATE TABLE batch_error_log (
    error_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id    NUMBER,
    error_code        NUMBER,
    error_message     VARCHAR2(4000),
    failed_at         TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- Introducir intencionalmente unas pocas transacciones inconsistentes para estresar la captura de errores
UPDATE ledger_transactions 
SET amount = -500 
WHERE transaction_id IN (
    SELECT transaction_id 
    FROM ledger_transactions 
    WHERE status = 'PENDING' AND ROWNUM <= 25
);
COMMIT;

EXIT;
