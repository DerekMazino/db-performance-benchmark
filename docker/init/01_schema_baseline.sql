-- Asegurar que la PDB esté abierta y cambiar el contexto
ALTER PLUGGABLE DATABASE FREEPDB1 OPEN;
ALTER SESSION SET CONTAINER = FREEPDB1;

-- Crear el usuario local en FREEPDB1
CREATE USER BENCHMARK_USER IDENTIFIED BY "Benchmark2026!"
DEFAULT TABLESPACE USERS
TEMPORARY TABLESPACE TEMP
QUOTA UNLIMITED ON USERS;

-- Privilegios de desarrollo, administración de espacio y monitoreo de rendimiento
GRANT CONNECT, RESOURCE TO BENCHMARK_USER;
GRANT UNLIMITED TABLESPACE TO BENCHMARK_USER;
GRANT CREATE VIEW, CREATE TABLE, CREATE PROCEDURE TO BENCHMARK_USER;
GRANT SELECT_CATALOG_ROLE TO BENCHMARK_USER;
GRANT SELECT ANY DICTIONARY TO BENCHMARK_USER;

-- Cambiar al esquema recién creado para las tablas
ALTER SESSION SET CURRENT_SCHEMA = BENCHMARK_USER;

-- Tabla de Cuentas (Dimensión)
CREATE TABLE accounts (
    account_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number   VARCHAR2(34) NOT NULL UNIQUE,
    account_type     VARCHAR2(20) NOT NULL,
    current_balance  NUMBER(15, 2) DEFAULT 0.00 NOT NULL,
    created_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- Tabla de Transacciones (Ledger) - Sin índices secundarios para el baseline inicial
CREATE TABLE ledger_transactions (
    transaction_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id        NUMBER NOT NULL,
    transaction_date  TIMESTAMP NOT NULL,
    transaction_type  VARCHAR2(20) NOT NULL,
    amount            NUMBER(12, 2) NOT NULL,
    status            VARCHAR2(20) NOT NULL,
    payload_metadata  VARCHAR2(250),
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_ledger_account FOREIGN KEY (account_id) REFERENCES accounts(account_id)
);